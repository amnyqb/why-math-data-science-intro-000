#!/usr/bin/env python3
"""F1 (seasonal naive) against F2 (AutoETS from augurs) on the 70 M5 series, rolling origin over the test window.

    python3 run_forecasts.py        # builds and runs forecast/, writes results/forecast_*.csv and B1_forecasts.md

Origins are weeks 225, 229, ..., 273 (13 origins), horizon 4 weeks, so every test week 225..276 is forecast.
Both methods see only the weeks before the origin. Series are scaled by the training mean (weeks 0..224) to 100.
Scores: RMSSE (Competitors Guide, p. 6: squared error over the squared one-step naive error of the training
history) and the pinball loss over the nine M5 quantiles, scaled by the mean absolute one-step naive error.
"""

import csv
import math
import os
import statistics
import subprocess

import run_pilot as rp

HERE = rp.HERE
DATA = os.path.join(HERE, "data", "m5_store_department_weekly.csv")
BIN = os.path.join(HERE, "forecast", "target", "release", "b1-forecast")
F2 = os.path.join(HERE, "build", "f2_augurs.csv")
FIRST, STEP, H, SEASON = 225, 4, 4, 52
QS = [0.005, 0.025, 0.165, 0.25, 0.5, 0.75, 0.835, 0.975, 0.995]


def pinball(y, q, tau):
    return tau * (y - q) if y >= q else (1 - tau) * (q - y)


def quantile(xs, p):
    return rp.percentile(xs, p)


def main():
    os.makedirs(rp.BUILD, exist_ok=True)
    subprocess.run([BIN, DATA, F2, str(FIRST), str(STEP), str(H)], check=True)
    series = {}
    for r in csv.DictReader(open(DATA)):
        series.setdefault((r["store_id"], r["dept_id"]), []).append(float(r["units"]))
    f2 = {}
    for r in csv.DictReader(open(F2)):
        f2[((r["store"], r["dept"]), int(r["origin"]), int(r["horizon"]))] = [float(r[k]) for k in ("q005", "q025", "q165", "q250", "point", "q750", "q835", "q975", "q995")]
    rows = []
    for key, units in sorted(series.items()):
        mean = statistics.mean(units[:FIRST])
        y = [u * 100 / mean for u in units]
        train = y[:FIRST]
        d1 = [abs(train[i] - train[i - 1]) for i in range(1, FIRST)]
        scale_abs, scale_sq = statistics.mean(d1), statistics.mean([(train[i] - train[i - 1]) ** 2 for i in range(1, FIRST)])
        se = {"F1": [], "F2": []}
        pl = {"F1": [], "F2": []}
        for t in range(FIRST, len(y) - H + 1, STEP):
            # seasonal naive residuals up to the origin give the quantiles of F1
            res = [y[w] - y[w - SEASON] for w in range(SEASON, t)]
            qres = [quantile(res, p) for p in QS]
            for h in range(1, H + 1):
                actual = y[t + h - 1]
                base = y[t + h - 1 - SEASON]
                f1 = [base + qr for qr in qres]
                f1[4] = base
                f2q = f2.get((key, t, h))
                if f2q is None:
                    continue
                se["F1"].append((actual - base) ** 2)
                se["F2"].append((actual - f2q[4]) ** 2)
                pl["F1"].append(statistics.mean(pinball(actual, q, tau) for q, tau in zip(f1, QS)))
                pl["F2"].append(statistics.mean(pinball(actual, q, tau) for q, tau in zip(f2q, QS)))
        rows.append({"store": key[0], "dept": key[1], "points": len(se["F1"]),
                     "F1_RMSSE": math.sqrt(statistics.mean(se["F1"]) / scale_sq), "F2_RMSSE": math.sqrt(statistics.mean(se["F2"]) / scale_sq),
                     "F1_SPL": statistics.mean(pl["F1"]) / scale_abs, "F2_SPL": statistics.mean(pl["F2"]) / scale_abs})
    rp.write_csv("forecast_scores.csv", [{k: (round(v, 6) if isinstance(v, float) else v) for k, v in r.items()} for r in rows])
    comp = []
    for m in ("RMSSE", "SPL"):
        a = [r[f"F2_{m}"] for r in rows]
        b = [r[f"F1_{m}"] for r in rows]
        rel = [(x - y) / y for x, y in zip(a, b)]
        w = rp.wilcoxon(rel)
        comp.append({"measure": m, "F1_median": statistics.median(b), "F2_median": statistics.median(a), "median_rel_diff_F2_vs_F1": statistics.median(rel),
                     "p05": rp.percentile(rel, .05), "p95": rp.percentile(rel, .95), "share_F2_better": sum(1 for x in rel if x < 0) / len(rel), "wilcoxon_p": w["p"]})
    rp.write_csv("forecast_comparison.csv", [{k: (round(v, 6) if isinstance(v, float) else v) for k, v in r.items()} for r in comp])
    L = ["# B1 forecasts: F1 (seasonal naive) against F2 (AutoETS from augurs)\n",
         "*Generated by `run_forecasts.py` on 19 November 2026. Rolling origin over the 52-week test window of the 70 M5 store-by-department series (origins at weeks 225, 229, ..., 273; horizon 4 weeks). Both methods see only the weeks before the origin. Scores are on the series scaled by the training mean.*\n",
         "## Setup\n",
         "- **F1** seasonal naive: the value 52 weeks earlier. Its quantiles are that value plus the empirical quantiles of the in-sample seasonal-naive errors up to the origin.",
         "- **F2** `augurs` 0.10.3 `AutoETS` with the search `ZZN`, i.e. **no seasonal component**: the crate documents that seasonal models are not implemented yet. It returns one symmetric interval per call, so the nine M5 quantiles come from four calls (levels 0.5, 0.67, 0.95, 0.99) read as the matching two-sided quantiles, and the median is the point forecast. That reading assumes normal errors; it is mine, not the crate's.",
         "- **RMSSE** as in the Competitors Guide (page 6); **scaled pinball loss** over the nine M5 quantiles, divided by the mean absolute one-step naive error of the training history. Lower is better.\n",
         "## Result\n", "| measure | F1 median | F2 median | median relative difference (F2 vs F1) | 90% interval over series | share of series F2 is better | Wilcoxon p |\n|---|---|---|---|---|---|---|"]
    for c in comp:
        L.append(f"| {c['measure']} | {c['F1_median']:.3f} | {c['F2_median']:.3f} | {100 * c['median_rel_diff_F2_vs_F1']:+.1f}% | {100 * c['p05']:+.1f}% to {100 * c['p95']:+.1f}% | {c['share_F2_better']:.2f} | {c['wilcoxon_p']:.3g} |")
    r0 = comp[0]
    L.append("")
    L.append(("F2 does **not** beat the seasonal naive floor on point accuracy: " if r0["median_rel_diff_F2_vs_F1"] >= 0 else "F2 beats the seasonal naive floor on point accuracy: ") +
             f"median RMSSE {r0['F2_median']:.3f} against {r0['F1_median']:.3f}. The criteria say to report this either way (CRITERIA.md section 6, item 4).\n")
    L.append("## Caveats\n")
    L.append("- F2 has no seasonality, and these series have a strong yearly cycle; this is a limit of the crate version, not of exponential smoothing. A seasonal ETS (for example through MSTL, which the crate offers separately) was not tried.")
    L.append("- The forecasts are scored but **do not feed the policy runs**: the ordering policies in `B1_M5_report.md` use no forecast input. Whether a better forecast lowers cost is not tested here.")
    L.append("- The quantile mapping for F2 is an assumption (above); pinball scores depend on it.")
    open(os.path.join(HERE, "B1_forecasts.md"), "w").write("\n".join(L) + "\n")
    for c in comp:
        print(c)


if __name__ == "__main__":
    main()
